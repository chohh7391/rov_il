"""Configuration for the parametric "Bravo 7-class" underwater manipulator (Isaac Lab 3.0).

The arm is our own design built from public Reach Bravo 7 specifications only (6 rotary DOF + parallel
jaws, 0.9 m reach, 92 mm OD, 9.5 kg in air / 4.5 kg in water, 20 N*m / 68 deg/s wrist rotate, 80 kgf
grab). Geometry, masses and limits are generated by ``rov_lab/scripts/tools/make_bravo7_class_urdf.py``;
the USD is produced by ``rov_lab/scripts/tools/convert_bravo7_class.py``.

Frames: ``base_link`` origin is the centre of the mounting-flange face, +z along the base-rotate axis
(away from the hull), +x the arm direction at the zero pose (fully extended). Pitch joints rotate about
-y, so positive angles raise the next link. ``jaw_base_link`` sits behind the fixed ``ft_sensor_joint``;
read the wrist wrench there with :class:`isaaclab.sensors.JointWrenchSensorCfg` (incoming joint frame).

Quaternions follow Isaac Lab 3.0, i.e. (x, y, z, w). Use a physics dt of 1/120 s or smaller for stiff
jaw contact. The root is fixed for standalone use; set ``spawn.fix_root_link`` (or attach ``base_link``
to the hull) when mounting the arm on an ROV.

Buoyancy is not part of the asset: apply ``rho * g * LINK_DISPLACED_VOLUME_M3[link]`` upward at
``LINK_CENTER_OF_BUOYANCY_M[link]`` (equal to each link's centre of mass in this model).

Drive caveat (measured in Isaac Sim 6.2 / PhysX, see ``rov_lab/scripts/tools/test_bravo7_class.py``): with the
solver joint velocity limits active, an implicit drive whose target is far beyond a blocked joint (PD demand
several times the effort limit) delivers well below its effort limit (``ee_roll_joint``: ~7 of 20 N*m). With
the target within ~1.3 * effort / stiffness of the joint it delivers the full limit (breakaway at 20 N*m).
Rate-limit position targets (teleop / policy actions) instead of commanding large steps against contact.
"""

