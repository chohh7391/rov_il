_LARGE: tuple[str, ...] = (BASE_YAW_JOINT, SHOULDER_PITCH_JOINT, ELBOW_PITCH_JOINT)
_WRIST: tuple[str, ...] = (FOREARM_ROLL_JOINT, WRIST_PITCH_JOINT, EE_ROLL_JOINT)

BRAVO7_CLASS_CFG: ArticulationCfg = ArticulationCfg(
    spawn=sim_utils.UsdFileCfg(
        usd_path=str(BRAVO7_CLASS_USD_PATH),
        activate_contact_sensors=False,
        fix_root_link=True,
        rigid_props=PhysxRigidBodyCfg(disable_gravity=False, max_depenetration_velocity=1.0),
        articulation_props=PhysxArticulationCfg(
            enabled_self_collisions=False, solver_position_iteration_count=16, solver_velocity_iteration_count=1
        ),
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, 0.0),
        rot=(0.0, 0.0, 0.0, 1.0),
        joint_pos=BRAVO7_CLASS_HOME_JOINT_POS,
        joint_vel={".*": 0.0},
    ),
    actuators={
        # base yaw / shoulder / elbow: ~42 W class modules, stiff position hold under 10 kg wet payload
        "bravo7_large": ImplicitActuatorCfg(
            joint_names_expr=list(_LARGE),
            joint_effort_limit=_limits(_LARGE, 3),
            joint_velocity_limit=_limits(_LARGE, 2),
            stiffness={BASE_YAW_JOINT: 2000.0, SHOULDER_PITCH_JOINT: 2500.0, ELBOW_PITCH_JOINT: 1500.0},
            damping={BASE_YAW_JOINT: 150.0, SHOULDER_PITCH_JOINT: 200.0, ELBOW_PITCH_JOINT: 100.0},
            armature=0.1,
            friction={BASE_YAW_JOINT: 1.0, SHOULDER_PITCH_JOINT: 1.5, ELBOW_PITCH_JOINT: 1.0},
            viscous_friction={BASE_YAW_JOINT: 2.0, SHOULDER_PITCH_JOINT: 3.0, ELBOW_PITCH_JOINT: 2.0},
        ),
        # forearm roll / wrist pitch / end-effector roll (20 N*m, 68 deg/s per spec)
        "bravo7_wrist": ImplicitActuatorCfg(
            joint_names_expr=list(_WRIST),
            joint_effort_limit=_limits(_WRIST, 3),
            joint_velocity_limit=_limits(_WRIST, 2),
            stiffness={FOREARM_ROLL_JOINT: 400.0, WRIST_PITCH_JOINT: 600.0, EE_ROLL_JOINT: 150.0},
            damping={FOREARM_ROLL_JOINT: 15.0, WRIST_PITCH_JOINT: 20.0, EE_ROLL_JOINT: 4.0},
            armature={FOREARM_ROLL_JOINT: 0.03, WRIST_PITCH_JOINT: 0.03, EE_ROLL_JOINT: 0.01},
            friction={FOREARM_ROLL_JOINT: 0.5, WRIST_PITCH_JOINT: 0.5, EE_ROLL_JOINT: 0.25},
            viscous_friction={FOREARM_ROLL_JOINT: 0.5, WRIST_PITCH_JOINT: 0.5, EE_ROLL_JOINT: 0.2},
        ),
        # parallel jaws, 785 N max per finger (80 kgf squeeze). The two drives are independent (no mimic), so
        # the grasp stays centred only while neither drive saturates: with a closed target (q = 0) the grip is
        # K * opening / 2, i.e. 700 N on a 40 mm object; drives saturate (no centring stiffness) above ~45 mm.
        "bravo7_jaws": ImplicitActuatorCfg(
            joint_names_expr=list(BRAVO7_CLASS_FINGER_JOINT_NAMES),
            joint_effort_limit=_limits(BRAVO7_CLASS_FINGER_JOINT_NAMES, 3),
            joint_velocity_limit=_limits(BRAVO7_CLASS_FINGER_JOINT_NAMES, 2),
            stiffness=3.5e4,
            damping=300.0,
            armature=2.0,  # reflected lead-screw inertia [kg]; also keeps the solver velocity clamp tight
            friction=5.0,
            viscous_friction=20.0,
        ),
    },
    soft_joint_pos_limit_factor=1.0,
)
"""Bravo 7-class arm on a fixed base (implicit PD position drives)."""
